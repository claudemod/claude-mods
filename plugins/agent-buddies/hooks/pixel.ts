// A space is this many pixels wide; every glyph is followed by one pixel of air.
const SPACE = 3
const FALLBACK = GLYPHS['?']!
// Glyph rows with the descender, and one more for the shadow.
export const TEXT_ROWS = 9

function glyph(ch: string) {
  return GLYPHS[ch] ?? FALLBACK
}

export function textWidth(text: string) {
  let width = 0
  for (const ch of text) width += (ch === ' ' ? SPACE : glyph(ch)[0]!.length) + 1
  return Math.max(0, width - 1)
}

// The text as path data for a one-pixel stroke: a line per run of lit pixels,
// its top-left at (x, y). Draw it with `stroke`, not `fill`.
export function textPath(text: string, x: number, y: number) {
  let d = ''
  let cx = x
  for (const ch of text) {
    if (ch === ' ') {
      cx += SPACE + 1
      continue
    }
    const rows = glyph(ch)
    rows.forEach((row, r) => {
      let c = 0
      while (c < row.length) {
        if (row[c] !== '#') {
          c++
          continue
        }
        let end = c
        while (row[end] === '#') end++
        d += `M${cx + c} ${y + r}.5h${end - c}`
        c = end
      }
    })
    cx += rows[0]!.length + 1
  }
  return d
}

// The darker colour a coloured text casts: a quarter of its brightness.
export function shadowOf(color: string) {
  const channel = (i: number) => (parseInt(color.slice(i, i + 2), 16) >> 2).toString(16).padStart(2, '0')
  return `#${channel(1)}${channel(3)}${channel(5)}`
}

// Cuts text into lines no wider than `width` pixels, at spaces.
export function wrap(text: string, width: number): string[] {
  const lines: string[] = []
  let line = ''
  for (const word of text.split(' ')) {
    const next = line ? `${line} ${word}` : word
    if (line && textWidth(next) > width) {
      lines.push(line)
      line = word
    } else {
      line = next
    }
  }
  if (line) lines.push(line)
  return lines
}

export type Ink = { color: string; hasShadow?: boolean }

export type Label = { source: string; width: number; height: number }

const labels = new Map<string, Label>()

// Lines of text as a picture, `scale` screen pixels to a font pixel.
export function labelSvg(lines: readonly string[], scale: number, ink: Ink, align: 'left' | 'center' = 'left'): Label {
  const key = `${lines.join('\n')}|${scale}|${ink.color}|${ink.hasShadow}|${align}`
  const cached = labels.get(key)
  if (cached) return cached
  const width = Math.max(1, ...lines.map(textWidth)) + 1
  const height = lines.length * TEXT_ROWS
  let shade = ''
  let face = ''
  lines.forEach((line, i) => {
    const x = align === 'center' ? Math.floor((width - 1 - textWidth(line)) / 2) : 0
    if (ink.hasShadow) shade += textPath(line, x + 1, i * TEXT_ROWS + 1)
    face += textPath(line, x, i * TEXT_ROWS)
  })
  const label = {
    width: width * scale,
    height: height * scale,
    source:
      `<svg xmlns='http://www.w3.org/2000/svg' width='${width * scale}' height='${height * scale}' viewBox='0 0 ${width} ${height}' shape-rendering='crispEdges'>` +
      (shade ? `<path stroke='${shadowOf(ink.color)}' d='${shade}'/>` : '') +
      `<path stroke='${ink.color}' d='${face}'/></svg>`,
  }
  labels.set(key, label)
  return label
}
