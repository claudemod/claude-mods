// A space is this many pixels wide; every glyph is followed by one pixel of air.
const SPACE = 3
const FALLBACK = GLYPHS['?']!

export const GLYPH_ROWS = 8

function glyph(ch: string) {
  return GLYPHS[ch] ?? FALLBACK
}

export function glyphNames() {
  return Object.keys(GLYPHS)
}

export function glyphRows(ch: string) {
  return GLYPHS[ch]
}

export function textWidth(text: string) {
  let width = 0
  for (const ch of text) width += (ch === ' ' ? SPACE : glyph(ch)[0]!.length) + 1
  return Math.max(0, width - 1)
}

// The text as one SVG path, a rectangle per run of lit pixels, its top-left at (x, y).
export function textPath(text: string, x: number, y: number) {
  let d = ''
  let cx = x

  for (const ch of text) {
    if (ch === ' ') {
      cx += SPACE + 1
      continue
    }

    const rows = glyph(ch)
    rows.forEach((row, r) => {
      let c = 0
      while (c < row.length) {
        if (row[c] !== '#') {
          c++
          continue
        }
        let end = c
        while (row[end] === '#') end++
        d += `M${cx + c} ${y + r}h${end - c}v1h${c - end}z`
        c = end
      }
    })
    cx += rows[0]!.length + 1
  }

  return d
}
